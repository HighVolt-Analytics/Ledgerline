type StepInput = {
  stageId: DossierPipelineStep["stageId"];
  state: DossierPipelineStep["state"];
  detail: string;
  at: string | null;
  actor?: string;
  durationMs?: number;
  exceptionCode?: string | null;
  failureReason?: string | null;
  remediation?: string | null;
  blockedReason?: string | null;
  checks?: DossierPipelineCheck[];
  evidence?: DossierPipelineEvidence[];
};

function pipeline(steps: StepInput[]): DossierPipelineStep[] {
  return steps.map((step) => ({
    stageId: step.stageId,
    state: step.state,
    detail: step.detail,
    at: step.at,
    actor: step.actor,
    durationMs: step.durationMs,
    exceptionCode: step.exceptionCode,
    failureReason: step.failureReason,
    remediation: step.remediation,
    blockedReason: step.blockedReason,
    checks: step.checks,
    evidence: step.evidence,
  }));
}

/** Shorthand for mock rows without per-check detail yet. */
function simplePipeline(
  states: Array<
    [DossierPipelineStep["stageId"], DossierPipelineStep["state"], string, string | null]
  >
): DossierPipelineStep[] {
  return pipeline(
    states.map(([stageId, state, detail, at]) => ({ stageId, state, detail, at }))
  );
}

function blockedAfter(failStage: string): string {
  return `Blocked — upstream stage "${failStage}" must pass before this stage can run.`;
}


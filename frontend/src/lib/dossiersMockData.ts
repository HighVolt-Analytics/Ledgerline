export const DOSSIER_RECENT_LIMIT = 12;

export function sortDossiersNewestFirst(rows: DossierSummary[]): DossierSummary[] {
  return [...rows].sort((a, b) => {
    const byDate = b.invoiceDate.localeCompare(a.invoiceDate);
    if (byDate !== 0) return byDate;
    return b.id.localeCompare(a.id);
  });
}

/** Newest dossiers first — capped for hero grid (matches upload recent list pattern). */
export function recentDossierCatalog(limit = DOSSIER_RECENT_LIMIT): DossierSummary[] {
  return sortDossiersNewestFirst(DOSSIER_MOCK_CATALOG).slice(0, limit);
}

export function getDossierById(id: string): DossierSummary | undefined {
  return DOSSIER_MOCK_CATALOG.find((row) => row.id === id);
}

export function dossierDocumentTypeOptions(): Array<{ value: string; label: string }> {
  const codes = [...new Set(DOSSIER_MOCK_CATALOG.map((row) => row.documentTypeCode))].sort();
  return [
    { value: "all", label: "All document types" },
    ...codes.map((code) => {
      const row = DOSSIER_MOCK_CATALOG.find((d) => d.documentTypeCode === code);
      return { value: code, label: row ? `${code} · ${row.documentTypeTitle}` : code };
    }),
  ];
}

